        modifier = Modifier
            .fillMaxSize()
            .background(
                Brush.verticalGradient(
                    colors = listOf(WhatsAppTealDark, DarkBg, DarkBg)
                )
            )
            .windowInsetsPadding(WindowInsets.safeDrawing),
        contentAlignment = Alignment.Center
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .widthIn(max = 520.dp)
                .verticalScroll(rememberScrollState())
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            Surface(
                modifier = Modifier.size(96.dp),
                shape = CircleShape,
                color = WhatsAppEmerald.copy(alpha = 0.16f)
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Image(
                        painter = painterResource(id = R.drawable.ic_whatsupp_logo),
                        contentDescription = "Whatsupp Logo",
                        modifier = Modifier.size(76.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            Text(
                text = "Whatsupp",
                style = MaterialTheme.typography.headlineLarge,
                color = Color.White,
                fontWeight = FontWeight.Bold
            )

            Text(
                text = "Family Device Connection & Live Monitor",
                style = MaterialTheme.typography.bodyLarge,
                color = WhatsAppEmerald,
                textAlign = TextAlign.Center
            )

            Spacer(modifier = Modifier.height(8.dp))

            Text(
                text = "Sign in with the same Google account on two phones: set one as Main Device (Controller) and the second as Connected Device.",
                style = MaterialTheme.typography.bodyMedium,
                color = Color(0xFFB8C7CE),
                textAlign = TextAlign.Center
            )

            Spacer(modifier = Modifier.height(24.dp))

            Card(
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(20.dp),
                colors = CardDefaults.cardColors(containerColor = DarkCard)
            ) {
                Column(
                    modifier = Modifier.padding(20.dp),
                    verticalArrangement = Arrangement.spacedBy(14.dp)
                ) {
                    FeatureRow(
                        icon = Icons.Default.PhonelinkSetup,
                        title = "Dual-Phone Role Pairing",
                        subtitle = "Link Main Controller & Connected Device with 6-digit consent verification"
                    )
                    FeatureRow(
                        icon = Icons.Default.CameraAlt,
                        title = "Live Camera & Consent Indicators",
                        subtitle = "Front & back CameraX viewing with mandatory visible privacy indicators"
                    )
                    FeatureRow(
                        icon = Icons.Default.Mic,
                        title = "Live Audio & Two-Way Voice",
                        subtitle = "Real-time microphone stream & full-duplex family intercom"
                    )
                    FeatureRow(
                        icon = Icons.Default.LocationOn,
                        title = "Real-Time GPS, Battery & Vault",
                        subtitle = "Live GPS coordinates, battery health, and AES-256-GCM encrypted local vault"
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))

            if (errorMessage != null) {
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(bottom = 16.dp),
                    colors = CardDefaults.cardColors(containerColor = Color(0xFF3E1A1A)),
                    shape = RoundedCornerShape(14.dp)
                ) {
                    Text(
                        text = errorMessage!!,
                        style = MaterialTheme.typography.bodyMedium,
                        color = Color(0xFFFFB4AB),
                        modifier = Modifier.padding(14.dp)
                    )
                }
            }

